"""Cross-run analysis: one results document over every graded run.

uv run python -m factbase.eval.analyze --runs v1,v2,v3,v4 --out docs/results.md
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from math import comb
from pathlib import Path

from ..paths import RUNS_DIR, ledger_rows, read_jsonl

ROOT = Path(__file__).resolve().parents[2]
DATASETS = ["markets", "football", "sec_filings", "fedreg", "world_quiz", "iran_headlines"]
ORDER = [
    "agentic_sql_v5", "factbase_v4", "agentic_sql_v4", "factbase_v3", "agentic_sql_v3", "factbase_v2", "agentic_sql", "factbase_v2_nostruct",
    "factbase", "agentic_raw", "raw_rag", "factbase_noagent", "factbase_noraw", "factbase_nostruct", "factbase_nodigest",
    "fact_memory", "rollups", "recent_window", "rolling_summary", "closed_book",
]
LABEL = {
    "agentic_sql_v5": "agentic_sql v5 (v4 + calibrated answer rules; exploratory, 2 datasets)",
    "factbase_v4": "factbase v4 (v3 + abstain guard)",
    "agentic_sql_v4": "agentic_sql v4 (v3 + abstain guard)",
    "factbase_v3": "factbase v3 (v2 + compute enforced)",
    "agentic_sql_v3": "agentic_sql v3 (raw rows + SQL/python, compute enforced)",
    "factbase_v2": "factbase v2 (all layers + SQL rows + python)",
    "agentic_sql": "agentic_sql v2 (raw rows + SQL/python, no facts/digests)",
    "factbase_v2_nostruct": "factbase v2 without structured fields",
    "factbase": "factbase v1 (pre-registered)",
    "agentic_raw": "agentic_raw (search agent over raw)",
    "raw_rag": "raw_rag (hybrid top-k, single shot)",
    "factbase_noagent": "factbase v1, no agent",
    "factbase_noraw": "factbase v1, no raw evidence",
    "factbase_nostruct": "factbase v1, no structured records",
    "factbase_nodigest": "factbase v1, no digests",
    "fact_memory": "fact_memory (extracted facts only)",
    "rollups": "rollups (frozen day/week/month digests)",
    "recent_window": "recent_window (last ~30k tokens)",
    "rolling_summary": "rolling_summary (auto-compaction)",
    "closed_book": "closed_book (no memory)",
}


def load(runs: list[str]) -> list[dict]:
    rows = []
    for run in runs:
        files = sorted({str(p).removesuffix(".gz") for p in (RUNS_DIR / run).glob("*/*.graded.jsonl*")})
        for f in map(Path, files):
            for r in read_jsonl(f):
                r.setdefault("stream", f.parent.name)
                rows.append(r)
    # one row per (stream, arch, qid): later runs never redefine an arch, but closed_book appears in several runs
    seen, out = set(), []
    for r in rows:
        k = (r["stream"], r["arch"], r["qid"])
        if k not in seen:
            seen.add(k)
            out.append(r)
    return out


def pct(ok: int, n: int) -> str:
    return f"{100 * ok / n:.1f}%" if n else "–"


def mcnemar(b: int, c: int) -> float:
    """Exact two-sided McNemar p-value from discordant counts."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    p = sum(comb(n, i) for i in range(0, k + 1)) / 2**n
    return min(1.0, 2 * p)


def ingest_costs() -> dict:
    """USD spent at ingestion time per (dataset, component) from the ledger (first-time calls only; cache hits are free)."""
    cost: dict = defaultdict(float)
    for r in ledger_rows():
        t = r["tag"].split(":")
        if t[0] in ("extract", "rollup") and len(t) >= 2:
            cost[(t[1], t[0])] += r["usd"]
        elif t[0] == "mem" and len(t) >= 4 and t[3] == "compact":
            cost[(t[2], "compaction")] += r["usd"]
    return cost


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--runs", default="v1,v2,v3,v4,v5,v6")
    p.add_argument("--out", default="docs/results.md")
    a = p.parse_args()
    rows = load(a.runs.split(","))
    single = [r for r in rows if r["stream"] != "combined"]
    combined = [r for r in rows if r["stream"] == "combined"]
    archs = [x for x in ORDER if any(r["arch"] == x for r in single)]

    acc = defaultdict(lambda: [0, 0])
    for r in single:
        acc[(r["arch"], r["dataset"])][0] += int(r["correct"])
        acc[(r["arch"], r["dataset"])][1] += 1

    L = ["# Results", "", "Generated by `factbase/eval/analyze.py` from the graded runs " + ", ".join(f"`{x}`" for x in a.runs.split(",")) + ".", "",
         "Run ids: `v1` = pre-registered architectures; `v2`, `v3` = factbase/agentic_sql v2 and v3 (designed after reading v1",
         "failures on markets, football, sec_filings and fedreg; world_quiz and iran_headlines were held out); `v4` = the combined",
         "stream; `v5` = architecture v4 (abstain guard); `v6` = architecture v5 (calibrated answer rules, exploratory, designed after",
         "reading iran_headlines failures).", ""]

    # main table
    L += ["## Accuracy by architecture and dataset", "",
          "Mean = unweighted mean over the datasets the architecture ran on (each dataset has 242-265 questions).", "",
          "| architecture | " + " | ".join(DATASETS) + " | mean |", "|---" * (len(DATASETS) + 2) + "|"]
    for ar in archs:
        cells, vals = [], []
        for d in DATASETS:
            ok, n = acc[(ar, d)]
            cells.append(pct(ok, n))
            if n:
                vals.append(ok / n)
        mean = f"**{100 * sum(vals) / len(vals):.1f}%** ({len(vals)})" if vals else "–"
        L.append(f"| {LABEL.get(ar, ar)} | " + " | ".join(cells) + f" | {mean} |")
    L.append("")

    # category table
    cats = ["point_recent", "point_old", "as_of_state", "change", "aggregate", "ordering", "multi_hop", "abstain"]
    cacc = defaultdict(lambda: [0, 0])
    for r in single:
        cacc[(r["arch"], r["category"])][0] += int(r["correct"])
        cacc[(r["arch"], r["category"])][1] += 1
    L += ["## Accuracy by question category (all datasets pooled)", "",
          "| architecture | " + " | ".join(cats) + " |", "|---" * (len(cats) + 1) + "|"]
    for ar in archs:
        L.append(f"| {ar} | " + " | ".join(f"{pct(*cacc[(ar, c)])} ({cacc[(ar, c)][1]})" for c in cats) + " |")
    L.append("")

    # retention
    ages = ["0-1m", "1-4m", "4-8m", "8-14m", "14m+"]
    racc = defaultdict(lambda: [0, 0])
    for r in single:
        if r["category"] in ("point_recent", "point_old"):
            racc[(r["arch"], r["age"])][0] += int(r["correct"])
            racc[(r["arch"], r["age"])][1] += 1
    L += ["## Retention: point-fact accuracy by age of the fact when asked", "",
          "| architecture | " + " | ".join(ages) + " |", "|---" * (len(ages) + 1) + "|"]
    for ar in archs:
        L.append(f"| {ar} | " + " | ".join(f"{pct(*racc[(ar, g)])} ({racc[(ar, g)][1]})" for g in ages) + " |")
    L.append("")

    # paired comparisons
    by = defaultdict(dict)
    for r in single:
        by[r["arch"]][(r["stream"], r["qid"])] = r["correct"]
    pairs = [
        ("agentic_sql_v5", "agentic_sql_v4"), ("agentic_sql_v4", "agentic_sql_v3"), ("factbase_v4", "agentic_sql_v4"),
        ("factbase_v3", "agentic_raw"), ("agentic_sql_v3", "agentic_raw"),
        ("factbase_v3", "agentic_sql_v3"), ("agentic_sql_v3", "agentic_sql"), ("factbase_v3", "factbase_v2"),
        ("factbase_v2", "agentic_sql"), ("factbase_v2", "factbase"), ("agentic_sql", "agentic_raw"),
        ("factbase_v2", "factbase_v2_nostruct"),
        ("factbase", "agentic_raw"), ("agentic_raw", "raw_rag"), ("raw_rag", "fact_memory"), ("raw_rag", "rollups"),
        ("factbase", "factbase_noagent"), ("factbase", "factbase_noraw"), ("raw_rag", "rolling_summary"),
        ("rolling_summary", "recent_window"),
    ]
    L += ["## Paired comparisons (same questions)", "",
          "A wins / B wins = questions only A (or only B) answered correctly. p = exact two-sided McNemar test.", "",
          "| A | B | shared questions | A acc | B acc | A wins | B wins | p |", "|---|---|---|---|---|---|---|---|"]
    for x, y in pairs:
        if x not in by or y not in by:
            continue
        keys = set(by[x]) & set(by[y])
        if not keys:
            continue
        b = sum(1 for k in keys if by[x][k] and not by[y][k])
        c = sum(1 for k in keys if by[y][k] and not by[x][k])
        ax = sum(by[x][k] for k in keys)
        ay = sum(by[y][k] for k in keys)
        L.append(f"| {x} | {y} | {len(keys)} | {pct(ax, len(keys))} | {pct(ay, len(keys))} | {b} | {c} | {mcnemar(b, c):.3g} |")
    L.append("")

    # combined stream
    if combined:
        L += ["## Combined stream (all six feeds in one memory)", "",
              "Same questions answered by the same architecture with only its own feed (single) or with all six feeds mixed in",
              "one memory of about 361k items (combined).", "",
              "**iran_headlines rows are invalid in the combined stream and excluded from the totals**: that quiz was written from",
              "Wikipedia Current Events bullets, and the world_quiz feed *is* those bullets, so in the combined memory the source text",
              "of every iran question sits in another feed. The other five quizzes have no such overlap.", "",
              "| architecture | feed | questions | single | combined |", "|---|---|---|---|---|"]
        cb = defaultdict(dict)
        for r in combined:
            cb[r["arch"]][r["qid"]] = (r["correct"], r["dataset"])
        for ar in [x for x in ORDER if x in cb]:
            tot = [0, 0, 0]
            for d in DATASETS:
                qids = [q for q, (_, ds) in cb[ar].items() if ds == d]
                sq = [q for q in qids if (d, q) in by.get(ar, {})]
                if not qids:
                    continue
                c_ok = sum(cb[ar][q][0] for q in qids)
                s_ok = sum(by[ar][(d, q)] for q in sq)
                leak = d == "iran_headlines"
                L.append(f"| {ar} | {d}{' (leak, excluded)' if leak else ''} | {len(qids)} | {pct(s_ok, len(sq)) if sq else '–'} | {pct(c_ok, len(qids))} |")
                if not leak:
                    tot[0] += len(qids)
                    tot[1] += c_ok
                    tot[2] += s_ok
            L.append(f"| **{ar}** | five valid feeds | {tot[0]} | **{pct(tot[2], tot[0])}** | **{pct(tot[1], tot[0])}** |")
        L.append("")

    # cost
    cost = defaultdict(lambda: [0.0, 0, 0.0])
    for r in single:
        c = cost[r["arch"]]
        c[0] += r.get("usd") or 0
        c[1] += 1
        c[2] += r.get("latency_s") or 0
    L += ["## Answer-time cost and latency", "", "| architecture | USD per question | mean latency (s) |", "|---|---|---|"]
    for ar in archs:
        u, n, lat = cost[ar]
        L.append(f"| {ar} | {u / n:.4f} | {lat / n:.1f} |")
    L.append("")
    ic = ingest_costs()
    L += ["## Ingestion-time LLM cost per dataset (USD, paid once, shared via cache)", "",
          "extract = fact extraction (factbase v1/v2/v3, fact_memory); rollup = digests (factbase, rollups); compaction = rolling_summary.", "",
          "| dataset | extract | rollup | compaction |", "|---|---|---|---|"]
    for d in DATASETS + ["combined"]:
        L.append(f"| {d} | {ic.get((d, 'extract'), 0):.2f} | {ic.get((d, 'rollup'), 0):.2f} | {ic.get((d, 'compaction'), 0):.2f} |")
    L.append("")
    total = sum(r["usd"] for r in ledger_rows())
    L += [f"Total LLM spend for the whole project (dataset building, ingestion, answers, grading, pilots): **${total:.2f}**.", ""]
    out = ROOT / a.out
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
